"""Export the backend's core response contracts for frontend tools and fixtures.

No app import, lifespan, migration or network call. --check fails when the
committed schema/JSDoc artifacts drift from their authoritative Python models.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Any

from pydantic import BaseModel

from tools._bootstrap import configure_path, refuse_sealed_output

ROOT = Path(configure_path(backend=True))

from domains.archive.schemas import ReadVerdictOut, SetupOut  # noqa: E402
from domains.screener.schemas import ScreenerResponse  # noqa: E402
from domains.watchlist.router import WatchlistItem  # noqa: E402

MODELS: tuple[type[BaseModel], ...] = (ScreenerResponse, ReadVerdictOut, SetupOut, WatchlistItem)
DESTINATION = ROOT / "webapp/frontend/src/api"


def contracts() -> dict[str, Any]:
    return {model.__name__: model.model_json_schema() for model in MODELS}


def js_type(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return str(schema["$ref"]).rsplit("/", 1)[-1]
    if "anyOf" in schema:
        return "(" + "|".join(js_type(part) for part in schema["anyOf"]) + ")"
    if "enum" in schema:
        return "(" + "|".join(json.dumps(value) for value in schema["enum"]) + ")"
    kind = schema.get("type")
    if kind == "array":
        return f"Array<{js_type(schema.get('items', {}))}>"
    if kind == "object":
        extra = schema.get("additionalProperties")
        return f"Object<string, {js_type(extra)}>" if isinstance(extra, dict) else "Object"
    return {"integer": "number", "number": "number", "string": "string",
            "boolean": "boolean", "null": "null"}.get(str(kind), "unknown")


def render() -> dict[str, str]:
    schemas = contracts()
    definitions: dict[str, Any] = {}
    for schema in schemas.values():
        definitions.update(schema.get("$defs", {}))
    definitions.update(schemas)
    lines = ["// Generated by python -m tools.audits.api_contracts --write. Do not edit."]
    for name, schema in definitions.items():
        if schema.get("type") != "object":
            lines.extend(["/**", f" * @typedef {{{js_type(schema)}}} {name}", " */"])
            continue
        required = schema.get("required", [])
        lines.extend(["/**", f" * @typedef {{Object}} {name}"])
        for field, spec in schema.get("properties", {}).items():
            label = field if field in required else f"[{field}]"
            lines.append(f" * @property {{{js_type(spec)}}} {label}")
        lines.append(" */")
    lines.append("export {};\n")
    return {"contracts.schema.json": json.dumps(schemas, indent=2, sort_keys=True) + "\n",
            "contracts.js": "\n".join(lines)}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    args = parser.parse_args()
    stale = []
    for name, content in render().items():
        path = DESTINATION / name
        if args.write:
            refuse_sealed_output(str(path))
            path.write_text(content, encoding="utf-8", newline="\n")
        elif not path.exists() or path.read_text(encoding="utf-8") != content:
            stale.append(name)
    if stale:
        print(f"STALE API contracts: {', '.join(stale)}; run with --write")
        return 1
    print("API contracts: generated" if args.write else "API contracts: current")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
